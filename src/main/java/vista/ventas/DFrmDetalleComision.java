    private void cargarDetalleVentas(int vendedorId, Date desde, Date hasta) {
        ComisionDAO dao = new ComisionDAO();
        List<Venta> lista = dao.obtenerVentasPorVendedorYFecha(vendedorId, desde, hasta);

        String[] columnas = {"ID", "Folio / N° Doc", "Tipo Documento", "Fecha", "Total ($)"};
        DefaultTableModel modelo = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Solo lectura
            }
        };

        double totalAcumulado = 0;

        for (Venta v : lista) {
            Object doc = (v.getNumeroDocumento() != null && !v.getNumeroDocumento().isEmpty())
                    ? v.getNumeroDocumento()
                    : (v.getFolio() > 0 ? v.getFolio() : v.getId());

            modelo.addRow(new Object[]{
                v.getId(),
                doc,
                v.getTipoDocumento(),
                sdf.format(v.getFechaEmision()),
                df.format(v.getTotal())
            });

            totalAcumulado += v.getTotal();
        }

        jTable1.setModel(modelo);
        jTable1.setRowHeight(25);

        // Formato para el Total
        lblTotalVentas.setFont(lblTotalVentas.getFont().deriveFont(Font.BOLD, 13f));
        lblTotalVentas.setForeground(new Color(0, 102, 204));
        lblTotalVentas.setText(df.format(totalAcumulado));
    }

    private void aplicarEfectoHoverPlano(javax.swing.JButton boton, java.awt.Color colorHover) {
        // 1. Cambiar el cursor a una manito
        boton.setCursor(new java.awt.Cursor(java.awt.Cursor.HAND_CURSOR));

        // Configuración base plana / sin bordes
        boton.setContentAreaFilled(false);
        boton.setBorderPainted(false);
        boton.setFocusPainted(false);

        // Eventos de entrada y salida del mouse
        boton.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseEntered(java.awt.event.MouseEvent evt) {
                boton.setContentAreaFilled(true); // Activa el fondo al pasar el cursor
                boton.setBackground(colorHover);
                boton.repaint();
            }

            @Override
            public void mouseExited(java.awt.event.MouseEvent evt) {
                boton.setContentAreaFilled(false); // Vuelve a ser transparente
                boton.repaint();
            }
        });
    }

