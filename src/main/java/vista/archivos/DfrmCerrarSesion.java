    private String obtenerFechaHoraActual() {
        DateTimeFormatter dtf = DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm");
        return LocalDateTime.now().format(dtf);
    }

    private void configurarVentana() {
        setLocationRelativeTo(null);
        setBackground(java.awt.Color.WHITE);

        lblUsuarioActual.setText(this.usuarioActual);
        lblSesionIniciada.setText(this.horaInicioSesion);

        // Agregamos el Hand Cursor (manito) a los botones
        btnCancelar.setCursor(new Cursor(Cursor.HAND_CURSOR));
        btnCerrarSesion.setCursor(new Cursor(Cursor.HAND_CURSOR));
    }

    private void botonCancelar() {
        if (menuLista != null) {
            menuLista.setVisible(true); // Vuelve a mostrar la ventana del menú
        }
        this.dispose(); 
    }

    private void botonCerrarSesion() {
        
        boolean confirmar = utilidades.AlertaUtil.mostrarConfirmacionCierreSesion(); 

        if (confirmar) {
            utilidades.SesionUsuario.limpiarSesion();

            vista.login.FrmLogin login = new vista.login.FrmLogin();
            login.setLocationRelativeTo(null);
            login.setVisible(true);

            this.dispose();

            java.awt.Window windows[] = java.awt.Window.getWindows();
            for (java.awt.Window window : windows) {
                if (window instanceof vista.FrmMenuPrincipal) {
                    window.dispose();
                }
            }
        }
    }

